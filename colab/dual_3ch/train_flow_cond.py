def build_cond_flow(base_kind, df, num_layers, num_bins, tail_bound,
                    hidden_features, num_blocks, context_features,
                    alpha_init=-5.0):
    """Build 1D Conditional NSF with macro context.

    base_kind ∈ {"skew_t", "student_t"} (normal 은 baseline 으로만 가치 있어 생략).
    """
    if base_kind == "skew_t":
        base = SkewTBase(shape=[1], alpha_init=alpha_init, df=df)
    elif base_kind == "student_t":
        base = StudentTBase(shape=[1], df=df)
    else:
        raise ValueError(f"unknown base_kind={base_kind}")

    transforms = []
    for _ in range(num_layers):
        transforms.append(MaskedPiecewiseRationalQuadraticAutoregressiveTransform(
            features=1,
            hidden_features=hidden_features,
            context_features=context_features,
            num_blocks=num_blocks,
            num_bins=num_bins,
            tails="linear",
            tail_bound=tail_bound,
        ))
    return Flow(CompositeTransform(transforms), base)


