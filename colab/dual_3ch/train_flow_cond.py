# Sanity check — sampled ε moments at C = 0 (train mean condition)
# =====================================================================

def sanity_at_mean_cond(flow, train_meta, device, n_sample=5000, seed=42):
    """Sample ε with context = 0 vector (= train mean cond after z-score).

    Compares to train ε empirical moments. At mean condition, the flow's marginal
    distribution should approximately match the unconditional train ε distribution.
    """
    flow.eval()
    torch.manual_seed(seed)
    K = len(train_meta["cond_features"])
    ctx = torch.zeros(1, K, device=device)   # 1 context → flow.sample broadcasts
    with torch.no_grad():
        # flow.sample(n, context) with context shape (B, K) returns (B, n, *event)
        eps_gen = flow.sample(n_sample, context=ctx).cpu().numpy().reshape(-1)

    def moments(x):
        m, s = float(np.mean(x)), float(np.std(x, ddof=1))
        if s < 1e-12:
            return m, s, float("nan"), float("nan")
        sk = float(np.mean((x - m) ** 3) / (s ** 3))
        kt = float(np.mean((x - m) ** 4) / (s ** 4) - 3.0)
        return m, s, sk, kt

    m, s, sk, kt = moments(eps_gen)
    print(f"\n  Sanity — sampled ε at mean cond (n={n_sample}):")
    print(f"    {'source':24s}  {'mean':>10s}  {'std':>8s}  {'skew':>8s}  {'ex_kurt':>10s}")
    print(f"    {'train ε empirical':24s}  "
          f"{0.0:+10.4f}  {1.0:>8.4f}  {train_meta['eps_skew']:+8.3f}  {train_meta['eps_ex_kurt']:+10.3f}")
    print(f"    {'Flow @ mean cond':24s}  {m:+10.4f}  {s:>8.4f}  {sk:+8.3f}  {kt:+10.3f}")

    se_skew = math.sqrt(6.0 / n_sample)
    se_kurt = math.sqrt(24.0 / n_sample)
    print(f"    SE(skew)≈{se_skew:.3f},  SE(ex_kurt)≈{se_kurt:.3f}")

    d_sk = sk - train_meta['eps_skew']
    d_kt = kt - train_meta['eps_ex_kurt']
    return dict(
        gen_mean=m, gen_std=s, gen_skew=sk, gen_ex_kurt=kt,
        delta_skew=d_sk, delta_ex_kurt=d_kt,
        se_skew=se_skew, se_kurt=se_kurt,
    )


