def _load_oof_csv(path, new_col_name):
    """Load OOF CSV (date, pred_log_std_oof) and rename pred column.

    Returns dataframe with columns ['date', new_col_name].
    """
    df = pd.read_csv(path, parse_dates=["date"])
    if "pred_log_std_oof" not in df.columns:
        raise KeyError(f"OOF CSV {path} missing column 'pred_log_std_oof'")
    out = df[["date", "pred_log_std_oof"]].rename(columns={"pred_log_std_oof": new_col_name})
    return out


def extract_eps_and_cond(train_csv, cond_features=COND_FEATURES_MACRO,
                         oof_specs=None):
    """Build (ε, C) training pairs.

    oof_specs : list of (col_name, csv_path) — appended to cond_features after macro.
                ε / r 는 row 단위, OOF prediction 은 origin date 단위 (= csv row index
                t+PAST_LEN-1). 대부분 row 가 origin 이므로 left-join 후 dropna 로 손실 최소.

    Returns (eps_t, cond_t, meta) where cond_features includes appended OOF columns.
    """
    df = pd.read_csv(train_csv, parse_dates=["date"])
    # If OOF specs provided, left-join by date and extend cond_features
    full_cond_features = list(cond_features)
    if oof_specs:
        for col, path in oof_specs:
            oof_df = _load_oof_csv(path, col)
            df = df.merge(oof_df, on="date", how="left")
            full_cond_features.append(col)
            print(f"  joined OOF: {col} ← {path}  "
                  f"(non-NaN: {df[col].notna().sum()}/{len(df)})")

    missing = [c for c in ["sp_return"] + full_cond_features if c not in df.columns]
    if missing:
        raise KeyError(f"train CSV missing columns after OOF join: {missing}")

    sub = df[["sp_return"] + full_cond_features].dropna().reset_index(drop=True)
    n = len(sub)
    cond_features = full_cond_features  # update for downstream
    if n < 30:
        raise RuntimeError(f"too few non-NaN train rows: {n}")

    r = sub["sp_return"].values.astype(np.float64)
    cond_raw = sub[cond_features].values.astype(np.float64)   # (N, K)

    # r → ε (global standardization)
    r_mean = float(r.mean())
    r_std  = float(r.std(ddof=1))
    if r_std < 1e-12:
        raise RuntimeError(f"degenerate r_std={r_std}")
    eps = ((r - r_mean) / r_std).astype(np.float32)

    # C → z-score (per feature)
    cond_mean = cond_raw.mean(axis=0)                        # (K,)
    cond_std  = cond_raw.std(axis=0, ddof=1)                 # (K,)
    cond_std_safe = np.where(cond_std < 1e-12, 1.0, cond_std)
    cond = ((cond_raw - cond_mean) / cond_std_safe).astype(np.float32)   # (N, K)

    def moments(x):
        x = np.asarray(x, dtype=np.float64)
        m, s = float(x.mean()), float(x.std(ddof=1))
        if s < 1e-12:
            return m, s, float("nan"), float("nan")
        sk = float(((x - m) ** 3).mean() / (s ** 3))
        kt = float(((x - m) ** 4).mean() / (s ** 4) - 3.0)
        return m, s, sk, kt

    rm, rs, rsk, rkt = moments(r)
    em, es, esk, ekt = moments(eps)
    print(f"  sp_return:  n={n}, mean={rm:+.6f}, std={rs:.6f}, "
          f"skew={rsk:+.3f}, ex_kurt={rkt:+.3f}, min/max=[{r.min():+.4f},{r.max():+.4f}]")
    print(f"  ε (global): mean={em:+.4f}, std={es:.4f}, "
          f"skew={esk:+.3f}, ex_kurt={ekt:+.3f}, min/max=[{eps.min():+.3f},{eps.max():+.3f}]")
    print(f"\n  Cond features (z-scored):")
    for k, f in enumerate(cond_features):
        cm = float(cond[:, k].mean())
        cs = float(cond[:, k].std(ddof=1))
        rng_lo = float(cond[:, k].min())
        rng_hi = float(cond[:, k].max())
        raw_m = float(cond_mean[k])
        raw_s = float(cond_std[k])
        print(f"    {f:20s}  raw μ={raw_m:+10.4f} σ={raw_s:.5f}  "
              f"→ z mean={cm:+.4f} std={cs:.4f} range=[{rng_lo:+.2f},{rng_hi:+.2f}]")

    eps_t  = torch.from_numpy(eps)                  # (N,)
    cond_t = torch.from_numpy(cond)                 # (N, K)
    meta = dict(
        n=n, r_mean=rm, r_std=rs,
        raw_skew=rsk, raw_ex_kurt=rkt,
        eps_skew=esk, eps_ex_kurt=ekt,
        eps_min=float(eps.min()), eps_max=float(eps.max()),
        cond_features=list(cond_features),
        cond_mean=cond_mean.tolist(),
        cond_std=cond_std.tolist(),
    )
    return eps_t, cond_t, meta


