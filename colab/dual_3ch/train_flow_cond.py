"""Conditional 1D Neural Spline Flow on globally-standardized ε
with **macro condition vector C_t** as Flow context (paper main thesis).

Paper thesis (regime-conditional tail):
  ε ~ NSF( · | C_t )           — Conditional Spline (autoregressive with context)
  C_t = z-score normalized 7-dim macro vector at origin row
       [tbill_wr, m2_13w_cum_lag, ads_lag, cpi_13w_cum_lag, sp_std_13w,
        wti_wr, sp_log_std_13w]   (v14 cond 전체 매칭)
  base : Skew-t (Azzalini-Capitanio 2003), α learnable, df=5 (fixed)

ε 정의 (불변, unconditional train_flow_b_global.py 와 동일):
  ε = (r - r̄_train) / σ_train         (global, 단일 scalar 정규화)

Cond 정규화 (train 통계, fold-isolated):
  C_t_norm = (c_t - cond_mean_train) / cond_std_train     (per-feature z-score)

Why Conditional NSF + Skew-t base:
  • Skew-t base 는 marginal 기준 empirical skew −0.85 / kurt +6.75 capture (inductive bias)
  • Conditional spline 은 macro regime 에 따라 ε bulk/tail 모양을 시점별 조정
    (ex: 인플레/긴축기 → 왼쪽 꼬리 더 두꺼움)
  → "ε ~ Skew-t  base × per-regime spline correction" 의 의미

Architecture:
  nflows MaskedPiecewiseRationalQuadraticAutoregressiveTransform
    features=1, context_features=7,
    hidden_features=64, num_blocks=2, num_bins=16, tails="linear", tail_bound=10.0
  (features=1 이면 autoregressive masking 은 trivial — 사실상 pure conditional spline)
  num_layers = 6 (paper main)

Ckpt 형식 (호환성 + 자동 architecture 재구성):
  {
    "model_state": flow.state_dict(),
    "meta": {
        "base_kind": "skew_t",
        "df": 5.0,
        "alpha_init": -5.0, "alpha_final": <learned>,
        "num_layers": 6, "num_bins": 16, "tail_bound": 10.0, "hidden_features": 64,
        "cond_features": [...],
        "cond_mean":     [...],   # per-feature train mean
        "cond_std":      [...],   # per-feature train std (ddof=1)
        "r_mean_train":  ...,     # for sp_return reconstruction at sample time
        "r_std_train":   ...,
        "n_train":       ...,
    }
  }

Usage (per fold, fold-isolated train):
  python colab/dual_3ch/train_flow_cond.py \
      --train-csv data/folds_v33_vix_expanding/F1_train.csv \
      --save-name scenario_3m_flow_1d_cond_F1_skewt_df5.pt

Citation:
  Azzalini & Capitanio (2003). Distributions generated by perturbation of symmetry
    with emphasis on a multivariate skew t-distribution. JRSS-B 65(2), 367-389.
  Durkan, Bekasov, Murray, Papamakarios (2019). Neural Spline Flows. NeurIPS.
"""
