def train_cond_flow(eps, cond, save_path, base_kind, df, alpha_init,
                    num_layers, num_bins, tail_bound, hidden_features, num_blocks,
                    epochs, batch, lr, device, log_every=20):
    """Train conditional flow. Save with metadata. Auto-load if save_path exists."""
    K = cond.shape[1]
    if os.path.exists(save_path):
        print(f"  [SKIP] flow ckpt 이미 존재: {save_path}")
        state = torch.load(save_path, map_location=device, weights_only=False)
        meta = state["meta"]
        # K = source-of-truth = len(cond_features). context_features 키는 잘못 저장될 수 있음.
        K_meta = len(meta.get("cond_features", [])) or meta.get("context_features", K)
        flow = build_cond_flow(
            base_kind=meta.get("base_kind", base_kind),
            df=meta.get("df", df),
            num_layers=meta.get("num_layers", num_layers),
            num_bins=meta.get("num_bins", num_bins),
            tail_bound=meta.get("tail_bound", tail_bound),
            hidden_features=meta.get("hidden_features", hidden_features),
            num_blocks=meta.get("num_blocks", num_blocks),
            context_features=K_meta,
            alpha_init=meta.get("alpha_init", alpha_init),
        ).to(device)
        flow.load_state_dict(state["model_state"])
        print(f"    [load] base={meta.get('base_kind','?')}, layers={meta.get('num_layers','?')}, "
              f"bins={meta.get('num_bins','?')}, hidden={meta.get('hidden_features','?')}, "
              f"context_features={meta.get('context_features','?')}")
        # SKIP path: 호출측이 (flow, train_stats) tuple unpack 하므로 동일 형식 반환
        return flow, dict(
            n_params=sum(p.numel() for p in flow.parameters()),
            final_train_nll=meta.get("final_train_nll"),
            best_train_nll=meta.get("best_train_nll"),
            alpha_final=meta.get("alpha_final"),
            alpha_history=meta.get("alpha_history"),
            skipped=True,
        )

    flow = build_cond_flow(
        base_kind=base_kind, df=df, alpha_init=alpha_init,
        num_layers=num_layers, num_bins=num_bins, tail_bound=tail_bound,
        hidden_features=hidden_features, num_blocks=num_blocks,
        context_features=K,
    ).to(device)
    n_params = sum(p.numel() for p in flow.parameters())

    if base_kind == "skew_t":
        base_desc = f"skew_t(α_init={alpha_init:+.2f}, df={df})"
    else:
        base_desc = f"student_t(df={df})"
    print(f"  Cond NSF: base={base_desc}, layers={num_layers}, bins={num_bins}, "
          f"hidden={hidden_features}, blocks={num_blocks}, K_cond={K}, "
          f"tail={tail_bound}, params={n_params:,}")

    opt = torch.optim.Adam(flow.parameters(), lr=lr)
    eps_t  = eps.unsqueeze(-1).to(device)   # (N, 1)
    cond_t = cond.to(device)                # (N, K)
    N = eps_t.shape[0]
    print(f"  N (ε,C) = {N:,},  batch={batch},  epochs={epochs},  lr={lr}")

    best_nll = float("inf")
    alpha_history = [] if base_kind == "skew_t" else None
    for ep in range(1, epochs + 1):
        flow.train()
        perm = torch.randperm(N)
        losses = []
        for i in range(0, N, batch):
            idx = perm[i : i + batch]
            xb = eps_t[idx]
            cb = cond_t[idx]
            loss = -flow.log_prob(inputs=xb, context=cb).mean()
            opt.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(flow.parameters(), max_norm=5.0)
            opt.step()
            losses.append(loss.item())
        ep_loss = float(np.mean(losses))
        if ep_loss < best_nll:
            best_nll = ep_loss
        if alpha_history is not None:
            alpha_history.append(float(flow._distribution.alpha.detach().item()))
        if ep == 1 or ep % log_every == 0 or ep == epochs:
            a_str = ""
            if base_kind == "skew_t":
                a_str = f"  α={flow._distribution.alpha.detach().item():+.3f}"
            print(f"    flow ep{ep:>3d}: nll = {ep_loss:+.4f}   "
                  f"(best so far {best_nll:+.4f}){a_str}")

    alpha_final = None
    if base_kind == "skew_t":
        alpha_final = float(flow._distribution.alpha.detach().item())

    return flow, dict(
        n_params=n_params,
        final_train_nll=ep_loss,
        best_train_nll=best_nll,
        alpha_final=alpha_final,
        alpha_history=alpha_history,
    )


